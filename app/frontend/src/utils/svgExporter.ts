import JSZip from 'jszip';
import type { ProjectState, Glyph, FontMetrics } from '../types/font.ts';

export interface SvgExportResult {
  success: boolean;
  filename: string;
  byteLength: number;
  glyphCount: number;
  blobUrl: string;
  error?: string;
}

/**
 * Generates a clean, filesystem-safe filename for a glyph SVG
 */
export function buildGlyphSvgFilename(char: string, unicode?: string): string {
  let baseName = char;
  if (char === ' ') baseName = 'space';
  else if (char === '/') baseName = 'slash';
  else if (char === '\\') baseName = 'backslash';
  else if (char === ':') baseName = 'colon';
  else if (char === '*') baseName = 'asterisk';
  else if (char === '?') baseName = 'question';
  else if (char === '"') baseName = 'quote';
  else if (char === '\'') baseName = 'singlequote';
  else if (char === '<') baseName = 'less';
  else if (char === '>') baseName = 'greater';
  else if (char === '|') baseName = 'pipe';
  else if (char === '.') baseName = 'period';
  else if (char === ',') baseName = 'comma';
  else if (char === ';') baseName = 'semicolon';
  else if (char === '-') baseName = 'hyphen';
  else if (char === '!') baseName = 'exclamation';

  const caseSuffix = /[A-Z]/.test(char) ? '_upper' : /[a-z]/.test(char) ? '_lower' : '';
  const unicodeHex = unicode || ('U+' + char.charCodeAt(0).toString(16).toUpperCase().padStart(4, '0'));
  return `${baseName}${caseSuffix}_${unicodeHex}.svg`;
}

/**
 * Builds standalone SVG document markup for a glyph in 1000 UPM standard space
 */
export function buildGlyphSvgContent(options: {
  char: string;
  unicode?: string;
  svgPath: string;
  advanceWidth: number;
  upm: number;
  ascender: number;
  familyName?: string;
  styleName?: string;
}): string {
  const { char, unicode, svgPath, advanceWidth, upm, ascender, familyName, styleName } = options;
  const unicodeHex = unicode || ('U+' + char.charCodeAt(0).toString(16).toUpperCase().padStart(4, '0'));
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by Local Font Studio for '${familyName || 'My-Font'} ${styleName || 'Regular'}' -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${advanceWidth} ${upm}" width="${advanceWidth}" height="${upm}">
  <!-- Glyph: '${char === ' ' ? 'space' : char}' | Unicode: ${unicodeHex} | Advance: ${advanceWidth} | UPM: ${upm} -->
  <g transform="translate(0, ${ascender}) scale(1, -1)">
    ${svgPath ? `<path d="${svgPath}" fill="#000000" />` : '<!-- Empty spacing glyph -->'}
  </g>
</svg>
`;
}

/**
 * Exports a single glyph as an individual downloadable .svg vector file.
 */
export function exportSingleGlyphAsSvg(options: {
  glyph: Glyph;
  metrics: { upm: number; ascender: number; defaultAdvance?: number };
  familyName?: string;
  styleName?: string;
  customAdvanceWidth?: number;
  customSvgPath?: string;
}): { success: boolean; filename: string; svgContent: string; blobUrl?: string } {
  const { glyph, metrics, familyName, styleName, customAdvanceWidth, customSvgPath } = options;
  const char = glyph.char;
  const unicodeHex = glyph.unicode || ('U+' + char.charCodeAt(0).toString(16).toUpperCase().padStart(4, '0'));
  const filename = buildGlyphSvgFilename(char, unicodeHex);
  const upm = metrics.upm || 1000;
  const ascender = metrics.ascender || 800;
  const advanceWidth = Math.max(10, Math.round(customAdvanceWidth ?? glyph.advanceWidth ?? metrics.defaultAdvance ?? 600));
  const svgPath = customSvgPath ?? glyph.svgPath ?? '';

  const svgContent = buildGlyphSvgContent({
    char,
    unicode: unicodeHex,
    svgPath,
    advanceWidth,
    upm,
    ascender,
    familyName,
    styleName,
  });

  let blobUrl = '';
  if (typeof Blob !== 'undefined') {
    const blob = new Blob([svgContent], { type: 'image/svg+xml;charset=utf-8' });
    if (typeof URL !== 'undefined' && typeof URL.createObjectURL === 'function') {
      blobUrl = URL.createObjectURL(blob);
    }
  }

  if (blobUrl && typeof document !== 'undefined') {
    const link = document.createElement('a');
    link.href = blobUrl;
    link.download = filename;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    setTimeout(() => {
      URL.revokeObjectURL(blobUrl);
    }, 1000);
  }

  return {
    success: true,
    filename,
    svgContent,
    blobUrl,
  };
}

/**
 * Creates individual SVG files for all assigned glyphs in the project
 * and bundles them into a downloadable .zip archive.
 */
export async function exportGlyphsAsSvgZip(
  project: ProjectState,
  customFilename?: string
): Promise<SvgExportResult> {
  try {
    const zip = new JSZip();
    const upm = project.metrics.upm || 1000;
    const ascender = project.metrics.ascender || 800;
    const descender = project.metrics.descender || -200;
    const familyName = project.name || project.metadata?.family || 'My-Typeface';
    const styleName = project.metadata?.style || 'Regular';

    const sanitizedFamily = familyName.replace(/[^a-zA-Z0-9_-]/g, '-');
    const sanitizedStyle = styleName.replace(/[^a-zA-Z0-9_-]/g, '-');
    const folderName = `${sanitizedFamily}-${sanitizedStyle}`;
    const zipFilename = customFilename || `${sanitizedFamily}-${sanitizedStyle}-svg.zip`;

    const folder = zip.folder(folderName) || zip;
    let glyphCount = 0;
    const exportedGlyphsInfo: Array<{ char: string; name: string; unicode: string; filename: string; advanceWidth: number }> = [];

    const glyphs = Object.values(project.glyphs || {});

    glyphs.forEach((g: Glyph) => {
      // Export assigned glyphs or space
      if (!g.isAssigned && g.char !== ' ') return;

      const char = g.char;
      const unicodeHex = g.unicode || ('U+' + char.charCodeAt(0).toString(16).toUpperCase().padStart(4, '0'));
      const advanceWidth = Math.max(10, Math.round(g.advanceWidth || (char === ' ' ? (project.metrics.spaceWidth || 280) : project.metrics.defaultAdvance || 600)));

      const svgFileName = buildGlyphSvgFilename(char, unicodeHex);
      const svgContent = buildGlyphSvgContent({
        char,
        unicode: unicodeHex,
        svgPath: g.svgPath,
        advanceWidth,
        upm,
        ascender,
        familyName,
        styleName,
      });

      folder.file(svgFileName, svgContent);
      glyphCount++;
      exportedGlyphsInfo.push({
        char,
        name: g.name || char,
        unicode: unicodeHex,
        filename: svgFileName,
        advanceWidth,
      });
    });

    // Also include a manifest JSON file with complete typography metrics
    const manifest = {
      family: familyName,
      style: styleName,
      metrics: {
        upm,
        ascender,
        descender,
        capHeight: project.metrics.capHeight,
        xHeight: project.metrics.xHeight,
        lineGap: project.metrics.lineGap,
        defaultAdvance: project.metrics.defaultAdvance,
        spaceWidth: project.metrics.spaceWidth || 280,
      },
      exportedAt: new Date().toISOString(),
      glyphCount,
      glyphs: exportedGlyphsInfo,
    };
    folder.file('font-manifest.json', JSON.stringify(manifest, null, 2));

    // Generate ZIP blob and trigger browser download
    const zipBlob = await zip.generateAsync({ type: 'blob' });
    const blobUrl = (typeof URL !== 'undefined' && typeof URL.createObjectURL === 'function')
      ? URL.createObjectURL(zipBlob)
      : '';

    if (typeof document !== 'undefined') {
      const link = document.createElement('a');
      link.href = blobUrl;
      link.download = zipFilename;
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
    }

    return {
      success: true,
      filename: zipFilename,
      byteLength: zipBlob.size,
      glyphCount,
      blobUrl,
    };
  } catch (err: any) {
    return {
      success: false,
      filename: customFilename || 'glyphs.zip',
      byteLength: 0,
      glyphCount: 0,
      blobUrl: '',
      error: err?.message || String(err),
    };
  }
}
